/**
 * Snapshot data loading utilities for the dashboard (V2).
 *
 * Snapshots are shareable, immutable execution state captures.
 * They correspond to the /runs/[id] URL scheme described in the replay docs.
 */

import type { TraceRun } from "./traceTypes";

// ── Types ─────────────────────────────────────────────────────────

/** Shareable snapshot of an execution trace (docs/replay data model). */
export interface SnapshotData {
  snapshot_id: string;
  prompt: string;
  model: string;
  provider: string;
  pack: string;
  timestamp: string;
  metrics: {
    ttft_ms: number;
    tokens_per_second: number;
    total_tokens: number;
  };
  response: string;
  /** Full trace run data for rendering in TraceTimeline. */
  trace: TraceRun;
  /** Optional user note attached when saving. */
  note?: string;
}

/** Lightweight entry in the snapshot index manifest. */
export interface SnapshotIndexEntry {
  snapshot_id: string;
  model: string;
  provider: string;
  prompt: string;
  pack: string;
  timestamp: string;
  totalTimeMs: number;
  tokenCount: number;
  stepCount: number;
  note?: string;
}

export interface SnapshotManifest {
  version: string;
  generated_at: string;
  total_snapshots: number;
  snapshots: SnapshotIndexEntry[];
}

/** Response from POST /api/snapshots (create). */
export interface SnapshotCreateResponse {
  snapshot_id: string;
  url: string;
}

// ── ID generation ─────────────────────────────────────────────────

/** Generate a short, human-readable snapshot ID (e.g., "snap-a3k8"). */
export function generateSnapshotId(): string {
  const chars = "abcdefghijklmnopqrstuvwxyz0123456789";
  let result = "snap-";
  for (let i = 0; i < 4; i++) {
    result += chars[Math.floor(Math.random() * chars.length)];
  }
  return result;
}

/** Build the shareable URL for a snapshot. */
export function snapshotUrl(snapshotId: string): string {
  // Uses origin-relative URL so it works in both dev and prod
  if (typeof window !== "undefined") {
    return `${window.location.origin}/runs/${encodeURIComponent(snapshotId)}`;
  }
  return `/runs/${encodeURIComponent(snapshotId)}`;
}

// ── Convert a TraceRun to a SnapshotData ──────────────────────────

/**
 * Create a SnapshotData payload from a TraceRun for saving.
 * Extracts the response text from the last response-type step.
 */
export function traceRunToSnapshot(
  run: TraceRun,
  options?: { note?: string; provider?: string; totalTokens?: number },
): SnapshotData {
  const responseStep = [...run.steps]
    .reverse()
    .find((s) => s.type === "response");
  const tokenSteps = run.steps.filter((s) => s.type === "token");
  const tokenCount =
    options?.totalTokens ?? tokenSteps.reduce((sum, s) => sum + (s.detail?.split(" ").length ?? 0), 0);

  return {
    snapshot_id: generateSnapshotId(),
    prompt: run.prompt,
    model: run.model,
    provider: options?.provider ?? "unknown",
    pack: run.pack,
    timestamp: new Date().toISOString(),
    metrics: {
      ttft_ms: run.steps.length > 0 ? run.steps[0].timing_ms : 0,
      tokens_per_second:
        run.totalTimeMs > 0
          ? Math.round((tokenCount / run.totalTimeMs) * 1000)
          : 0,
      total_tokens: tokenCount,
    },
    response: responseStep?.detail ?? "",
    trace: run,
    note: options?.note,
  };
}

// ── SSR loaders ───────────────────────────────────────────────────

export function emptyManifest(): SnapshotManifest {
  return {
    version: "1.0.0",
    generated_at: new Date().toISOString(),
    total_snapshots: 0,
    snapshots: [],
  };
}

const SNAPSHOTS_DIR = "results/snapshots";

/**
 * Load the snapshot manifest (index of all saved snapshots).
 * SSR: checks public/snapshots/ first (prebuild), falls back to results/snapshots/ (CLI).
 * Browser: fetches /api/snapshots.
 */
export async function loadSnapshotManifest(): Promise<SnapshotManifest> {
  if (import.meta.env.SSR) {
    try {
      const fs = await import("fs");
      const path = await import("path");
      // Check public/snapshots/ first (generated by prebuild)
      const publicPath = path.resolve(
        process.cwd(),
        "public",
        "snapshots",
        "index.json",
      );
      const resultsPath = path.resolve(
        process.cwd(),
        SNAPSHOTS_DIR,
        "index.json",
      );
      try {
        const raw = fs.readFileSync(publicPath, "utf-8");
        return JSON.parse(raw) as SnapshotManifest;
      } catch {
        const raw = fs.readFileSync(resultsPath, "utf-8");
        return JSON.parse(raw) as SnapshotManifest;
      }
    } catch {
      return emptyManifest();
    }
  }

  try {
    const resp = await fetch("/api/snapshots");
    if (!resp.ok) return emptyManifest();
    return { version: "1.0.0", generated_at: "", total_snapshots: 0, snapshots: await resp.json() };
  } catch {
    return emptyManifest();
  }
}

/**
 * Load a single snapshot by ID.
 */
export async function loadSnapshot(
  snapshotId: string,
): Promise<SnapshotData | null> {
  if (import.meta.env.SSR) {
    try {
      const fs = await import("fs");
      const path = await import("path");
      const filePath = path.resolve(
        process.cwd(),
        SNAPSHOTS_DIR,
        `${snapshotId}.json`,
      );
      const raw = fs.readFileSync(filePath, "utf-8");
      return JSON.parse(raw) as SnapshotData;
    } catch {
      return null;
    }
  }

  try {
    const resp = await fetch(
      `/api/snapshots/${encodeURIComponent(snapshotId)}`,
    );
    if (!resp.ok) return null;
    return (await resp.json()) as SnapshotData;
  } catch {
    return null;
  }
}

/**
 * Save a snapshot and return its ID + URL.
 * SSR: writes to results/snapshots/ on the filesystem.
 * Browser: POSTs to /api/snapshots.
 */
export async function saveSnapshot(
  snapshot: SnapshotData,
): Promise<SnapshotCreateResponse> {
  if (import.meta.env.SSR) {
    try {
      const fs = await import("fs");
      const path = await import("path");
      const dirPath = path.resolve(process.cwd(), SNAPSHOTS_DIR);
      fs.mkdirSync(dirPath, { recursive: true });

      // Write snapshot file
      const filePath = path.resolve(dirPath, `${snapshot.snapshot_id}.json`);
      fs.writeFileSync(filePath, JSON.stringify(snapshot, null, 2));

      // Update manifest
      const manifestPath = path.resolve(dirPath, "index.json");
      let manifest: SnapshotManifest;
      try {
        const raw = fs.readFileSync(manifestPath, "utf-8");
        manifest = JSON.parse(raw);
      } catch {
        manifest = emptyManifest();
      }

      const entry: SnapshotIndexEntry = {
        snapshot_id: snapshot.snapshot_id,
        model: snapshot.model,
        provider: snapshot.provider,
        prompt: snapshot.prompt.slice(0, 100),
        pack: snapshot.pack,
        timestamp: snapshot.timestamp,
        totalTimeMs: snapshot.trace.totalTimeMs,
        tokenCount: snapshot.metrics.total_tokens,
        stepCount: snapshot.trace.steps.length,
        note: snapshot.note,
      };

      manifest.snapshots.unshift(entry);
      manifest.total_snapshots = manifest.snapshots.length;
      manifest.generated_at = new Date().toISOString();
      fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2));

      return {
        snapshot_id: snapshot.snapshot_id,
        url: snapshotUrl(snapshot.snapshot_id),
      };
    } catch (err) {
      console.error("Failed to save snapshot:", err);
      throw new Error("Failed to save snapshot");
    }
  }

  // Browser: POST to API
  const resp = await fetch("/api/snapshots", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(snapshot),
  });
  if (!resp.ok) {
    throw new Error(`Failed to save snapshot: ${resp.statusText}`);
  }
  return (await resp.json()) as SnapshotCreateResponse;
}
